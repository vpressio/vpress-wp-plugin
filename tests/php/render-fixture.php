<?php
/**
 * Writes admin/tests/fixtures/embed.html: chart #1's figure exactly as
 * vpress_render_figure() prints it, rendered through the PHPUnit shims with
 * the chart row and rows captured from the dev site (tests/php/fixtures/).
 * The a11y E2E spec (admin/tests/e2e/a11y.spec.js) and manual checks load it
 * outside WordPress, so the H4 server markup can be tested before it is
 * served by MAMP.
 *
 * Usage (plugin root):
 *   php tests/php/render-fixture.php          # prod: loads admin/dist (run `yarn build` first)
 *   php tests/php/render-fixture.php --dev    # dev: writes embed-dev.html for `yarn dev` on :5180
 *
 * Options: --rest=<url>  REST root the embed calls (default http://localhost:8888/wp-json/vpress/v1/).
 *
 * @package Vpress
 */

if ( 'cli' !== PHP_SAPI ) {
	exit( 1 );
}

require __DIR__ . '/bootstrap.php';

$options = getopt( '', array( 'dev', 'rest::' ) );
$dev     = isset( $options['dev'] );
$rest    = isset( $options['rest'] ) && is_string( $options['rest'] ) ? $options['rest'] : 'http://localhost:8888/wp-json/vpress/v1/';

$wpdb = new FakeWpdb();
$wpdb->on( '/vpresscore_charts WHERE id = 1$/', (object) array( 'id' => '1', 'dataset_id' => '2', 'title' => null, 'permissions' => 'public', 'value' => VpressFixtures::CHART_1_VALUE ) );
$wpdb->on( '/vpresscore_datasets WHERE id = 2$/', (object) array( 'slug' => VpressFixtures::DATASET_SLUG, 'source' => null ) );
$wpdb->on( '/^SHOW COLUMNS FROM `vpress_vpress_test_ventas`$/', VpressFixtures::real_columns() );
$wpdb->on( '/^SELECT .* FROM `vpress_vpress_test_ventas` as f1/', json_decode( file_get_contents( __DIR__ . '/fixtures/chart-1-rows.json' ), true ) );
$GLOBALS['wpdb'] = $wpdb;

$figure = vpress_render_figure( 1 );
if ( '' === $figure || false === strpos( $figure, 'vpress-figure__alt' ) ) {
	fwrite( STDERR, "render-fixture: the figure rendered without its text alternative\n" );
	exit( 1 );
}
$figure = str_replace( esc_url( rest_url( 'vpress/v1/' ) ), esc_url( $rest ), $figure );

if ( $dev ) {
	$head    = '';
	$scripts = '<script type="module" src="/@vite/client"></script>' . "\n" . '<script type="module" src="/src/embed.js"></script>';
	$how     = "  Dev check: `yarn dev` (from admin/), then open http://localhost:5180/tests/fixtures/embed-dev.html";
	$target  = 'embed-dev.html';
} else {
	$head    = '<link rel="stylesheet" href="/dist/css/embed.css">';
	$scripts = '<script type="module" src="/dist/js/embed.js"></script>';
	$how     = "  1. yarn build            (from admin/)\n  2. python3 -m http.server 5188 --directory admin   (from the plugin root)\n  3. open http://localhost:5188/tests/fixtures/embed.html\n  E2E: E2E_FIXTURE_URL=http://localhost:5188/tests/fixtures/embed.html yarn test:e2e a11y --no-deps";
	$target  = 'embed.html';
}

$html = <<<HTML
<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Vpress embed fixture</title>
<!--
  Generated by tests/php/render-fixture.php from vpress_render_figure(1); do not edit by hand.
  Chart data comes from the local WordPress REST API ({$rest}).
{$how}
-->
{$head}
<style>
  body { max-width: 860px; margin: 24px auto; padding: 0 16px; font: 16px/1.5 Georgia, serif; color: #222; }
</style>
</head>
<body>
<main>
<p>Texto de un artículo antes de la gráfica.</p>
{$figure}
<p>Texto después de la gráfica.</p>
</main>
{$scripts}
</body>
</html>

HTML;

$path = dirname( __DIR__, 2 ) . '/admin/tests/fixtures/' . $target;
file_put_contents( $path, $html );
fwrite( STDOUT, "wrote {$path}\n" );
